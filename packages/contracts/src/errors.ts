import { Type, type Static } from '@sinclair/typebox';

/**
 * The one shape every refusal answers in.
 *
 * `message` states the fact — what was refused and why. `remedy` states the
 * action that clears it, in the operator's own vocabulary ("Cancel the
 * issued challan, then amend the item"). The panel measurement that put
 * this field here: about three-quarters of the server's refusals stated a
 * fact and stopped, leaving the clerk holding a true sentence and no next
 * step.
 *
 * The two are deliberately separate rather than one longer message. A
 * message is written by the route that refused and belongs to that
 * refusal; a remedy belongs to the error CODE and is the same wherever
 * that code is thrown, which is what lets `apps/server/src/remedies.ts`
 * hold one reviewed sentence per code instead of the same advice drifting
 * across forty call sites.
 *
 * `remedy` is OPTIONAL and stays optional. Adding it is backward
 * compatible in both directions: a client built before it exists ignores
 * an unknown property, and a code with no reviewed remedy yet simply
 * omits the field rather than shipping filler.
 *
 * `code` stays a plain string HERE even though `ERROR_CODES` below now
 * declares the vocabulary. This schema is a Fastify RESPONSE schema, so
 * it also serialises the framework's own refusals — a `FST_ERR_VALIDATION`
 * 400 travels in this envelope — and an enum would make those refusals
 * unserialisable rather than merely undeclared. The vocabulary is enforced
 * where it can be enforced without lying about the wire: on `httpError`'s
 * argument, at every call site, by the type checker.
 */
export const ApiErrorSchema = Type.Object(
  {
    code: Type.String(),
    message: Type.String(),
    requestId: Type.String(),
    remedy: Type.Optional(Type.String()),
    details: Type.Optional(Type.Unknown()),
  },
  { additionalProperties: false },
);

export type ApiError = Static<typeof ApiErrorSchema>;

/**
 * The vocabulary of refusal codes this API answers with.
 *
 * Before this list existed, `httpError` took `code: string` and the
 * server had grown 323 distinct code spellings across 634 refusals with
 * nothing checking any of them. Nothing refused a typo, nothing refused a
 * second spelling of a refusal that already had one, and nothing told a
 * client which codes it may switch on: the reconciled review's API-design
 * dimension counted them as "323 undeclared error-code strings".
 *
 * So the codes are declared here, in the package both sides compile
 * against, and `apps/server/src/http.ts` types `httpError`'s second
 * argument as `ErrorCode`. A refusal whose code is not on this list is now
 * a type error at the call site rather than a string a client discovers in
 * production. Adding a genuinely new refusal means adding it here first,
 * which is the point — the list is the review surface.
 *
 * The list is longer than the count that prompted it, and that is the
 * finding rather than a slip. 323 was what a `httpError(` census could
 * see; 14 of those were second spellings and collapsed, leaving 309. The
 * type checker then found 56 more the census never could: codes raised
 * through the statutory adapter's `StatutoryProviderError`, through the
 * snapshot and IRN evidence errors, through the shared master-route
 * helper — including five the Whitebooks adapter assembled by string
 * interpolation (`WHITEBOOKS_${error.code}`), which no search for their
 * names would ever have found. Those 56 were reaching clients as 409s and
 * 502s the whole time. With the four the error handler mints itself,
 * 369 codes are declared.
 *
 * What is NOT here, deliberately:
 *
 *  - Fastify's own `FST_ERR_*` codes (schema validation, body-too-large).
 *    They are minted by the framework before any handler runs, travel in
 *    the same envelope, and are the framework's vocabulary rather than
 *    this product's. `apps/web/src/api.ts` translates `FST_ERR_VALIDATION`
 *    into operator prose; the rest reach the client as-is.
 *  - Better Auth's own refusals on `/api/auth/*`, for the same reason.
 *
 * `REQUEST_ERROR`, `INTERNAL_ERROR`, `DATABASE_UNAVAILABLE` and
 * `RATE_LIMITED` ARE here: the error handler and the throttle hook in
 * `app.ts` mint them itself, so they are this product's words.
 *
 * Naming rule, applied to the dedupe that produced this list:
 * a code names the REFUSAL, not the route that refused. Four spellings of
 * "that number already exists in this organisation" collapsed into one
 * `NUMBER_CONFLICT`; two spellings of "the evidence changed under the
 * renderer" collapsed into `RENDER_SOURCE_CHANGED`. Refusals that differ
 * in what the operator must do next stay distinct even when their
 * sentences rhyme — `MB_BILLED` (a billed Measurement Book cannot be
 * cancelled) and `MB_ALREADY_BILLED` (a second bill cannot be prepared)
 * are two different next actions, so they are two codes.
 */
