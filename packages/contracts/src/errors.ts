/** A refusal code this API is allowed to answer with. */
export type ErrorCode = (typeof ERROR_CODES)[number];

const ERROR_CODE_SET: ReadonlySet<string> = new Set(ERROR_CODES);

/** Whether a string read off the wire is a code from the declared
 * vocabulary. Clients narrow with this before switching on a code. */
export function isErrorCode(value: string): value is ErrorCode {
  return ERROR_CODE_SET.has(value);
}

